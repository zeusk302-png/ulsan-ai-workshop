export function intermediateHref(id = "purpose") {
  const unit = intermediateUnits.some(item => item.id === id) ? id : "purpose";
  return `#automation?course=intermediate&unit=${unit}`;
}

export function resolveIntermediateUnit(hash = "") {
  const params = new URLSearchParams(hash.split("?")[1] || "");
  return intermediateUnits.find(item => item.id === params.get("unit")) || intermediateUnits[0];
}
